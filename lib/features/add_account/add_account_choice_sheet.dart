import 'package:flutter/material.dart';
import '../../ui/tokens/app_colors.dart';
import '../../ui/tokens/app_radius.dart';
import '../../ui/tokens/app_spacing.dart';

/// Screen 3 — Add Account Choice Bottom Sheet (Phase 2 UI & UX).
class AddAccountChoiceSheet extends StatelessWidget {
  final VoidCallback onScanQrSelected;
  final VoidCallback onManualSetupSelected;

  const AddAccountChoiceSheet({
    super.key,
    required this.onScanQrSelected,
    required this.onManualSetupSelected,
  });

  static void show(
    BuildContext context, {
    required VoidCallback onScanQrSelected,
    required VoidCallback onManualSetupSelected,
  }) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(AppRadius.large)),
      ),
      builder: (context) => AddAccountChoiceSheet(
        onScanQrSelected: onScanQrSelected,
        onManualSetupSelected: onManualSetupSelected,
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    return SafeArea(
      child: SingleChildScrollView(
        padding: const EdgeInsets.all(AppSpacing.xxl24),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Center(
              child: Container(
                width: 40.0,
                height: 4.0,
                decoration: BoxDecoration(
                  color: isDark ? AppColors.darkBorder : AppColors.lightBorder,
                  borderRadius: BorderRadius.circular(2.0),
                ),
              ),
            ),
            const SizedBox(height: AppSpacing.lg16),
            Text(
              'Add Authenticator Account',
              style: theme.textTheme.titleLarge,
            ),
            const SizedBox(height: AppSpacing.sm8),
            Text(
              'Choose how you want to add your 2FA account setup configuration.',
              style: theme.textTheme.bodyMedium,
            ),
            const SizedBox(height: AppSpacing.xxl24),
            _ChoiceTile(
              icon: Icons.qr_code_scanner,
              title: 'Scan QR Code',
              description: 'Scan a standard setup QR code generated by your service.',
              onTap: () {
                Navigator.pop(context);
                onScanQrSelected();
              },
            ),
            const SizedBox(height: AppSpacing.md12),
            _ChoiceTile(
              icon: Icons.edit_note,
              title: 'Enter Setup Key Manually',
              description: 'Manually enter your issuer, account name, and secret key.',
              onTap: () {
                Navigator.pop(context);
                onManualSetupSelected();
              },
            ),
            const SizedBox(height: AppSpacing.md12),
          ],
        ),
      ),
    );
  }
}

class _ChoiceTile extends StatelessWidget {
  final IconData icon;
  final String title;
  final String description;
  final VoidCallback onTap;

  const _ChoiceTile({
    required this.icon,
    required this.title,
    required this.description,
    required this.onTap,
  });

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    final tileBg = isDark ? AppColors.darkSecondarySurface : AppColors.lightSecondarySurface;
    final borderColor = isDark ? AppColors.darkBorder : AppColors.lightBorder;

    return Material(
      color: tileBg,
      shape: RoundedRectangleBorder(
        borderRadius: AppRadius.mediumBorder,
        side: BorderSide(color: borderColor, width: 1.0),
      ),
      clipBehavior: Clip.antiAlias,
      child: InkWell(
        onTap: onTap,
        child: Padding(
          padding: const EdgeInsets.all(AppSpacing.lg16),
          child: Row(
            children: [
              Container(
                padding: const EdgeInsets.all(AppSpacing.md12),
                decoration: BoxDecoration(
                  color: AppColors.blueAccent.withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(10.0),
                ),
                child: Icon(icon, color: AppColors.blueAccent, size: 24.0),
              ),
              const SizedBox(width: AppSpacing.lg16),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      title,
                      style: theme.textTheme.titleMedium,
                    ),
                    const SizedBox(height: AppSpacing.xs4),
                    Text(
                      description,
                      style: theme.textTheme.bodyMedium,
                    ),
                  ],
                ),
              ),
              const Icon(Icons.chevron_right),
            ],
          ),
        ),
      ),
    );
  }
}
